#include <stdio.h>

int secondLow(int values[], int size);

int main() {
    int N, i, second, val[100];
    scanf("%d", &N);
    for (i = 0; i < N; i++) {
        scanf("%d", &val[i]);
    }
    second = secondLow(val, N);
    printf("%d", second);
    return 0;
}

int secondLow(int values[], int size) {
    int low1, low2 = -1;

    for (int i = 0; i < size; i++) {
        for (int j = i + 1; j < size; j++) {
            if (values[i] > values[j]) {
                int t = values[i];
                values[i] = values[j];
                values[j] = t;
            }
        }
    }

    low1 = values[0];

    for (int i = 0; i < size; i++) {
        if (values[i] > low1) {
            low2 = values[i];
            break;
        }
    }

    if (size == 1 || size == 0) {
        return -1;
    } else {
        return low2;
    }
}
