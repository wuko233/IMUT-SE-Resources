#include <stdio.h>

void funnel(int height, char tube);

int main() {
    int n;
    char ch;
    scanf("%d %c", &n, &ch);
    funnel(n, ch);
    return 0;
}

void funnel(int height, char tube) {
    for (int i = height; i > 0; i--) {
        for (int j = height; j > i; j--) {
            printf(" ");
        }
        for (int j = 0; j < i; j++) {
            printf("%c", tube - j);
        }
        for (int j = i - 2; j >= 0; j--) {
            printf("%c", tube - j);
        }
        printf("\n");
    }
}
