#include <stdio.h>

int main(void) {
    int time, price = 0;
    scanf("%d", &time);

    if (time <= 1) {
        price = 0;
    } else if (time <= 8) {
        price = time * 5;
    } else {
        price = 8 * 5 + (time - 8) * 10;
        if (price >= 300) {
            price = 300;
        }
    }

    printf("您停车%d小时，需要支付%d元", time, price);

    return 0;
}
