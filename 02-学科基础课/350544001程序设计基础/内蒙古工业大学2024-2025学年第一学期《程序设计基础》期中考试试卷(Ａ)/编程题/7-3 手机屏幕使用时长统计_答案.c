#include <stdio.h>

int main(void) {
    double sum = 0, avg = 0, status = 1;

    for (int i = 0; i < 7; i++) {
        int time;
        scanf("%d", &time);

        if (time < 0 || time > 1440) {
            printf("Invalid Value");
            status = 0;
            break;
        }

        sum += time;
    }

    if (status != 0) {
        avg = sum / 7;
        printf("%.1lf", avg);
    }

    return 0;
}
