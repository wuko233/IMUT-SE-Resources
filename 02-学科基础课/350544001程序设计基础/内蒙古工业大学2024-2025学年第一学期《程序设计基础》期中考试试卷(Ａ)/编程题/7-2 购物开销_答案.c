#include <stdio.h>

int main(void) {
    int cost = 0, price;

    for (int i = 0; i < 3; i++) {
        scanf("%d", &price);
        cost += price;
    }

    if (cost >= 400) {
        cost -= 30;
    } else if (cost >= 300) {
        cost -= 20;
    } else if (cost >= 200) {
        cost -= 15;
    } else if (cost >= 100) {
        cost -= 5;
    }

    printf("%d", cost);

    return 0;
}
