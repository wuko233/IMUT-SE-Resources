#include <stdio.h>

/* 函数声明 */
int sizuo(int number, int step);

int main() {
    int n, s;
    scanf("%d%d", &n, &s);
    printf("%d\n", sizuo(n, s));
    return 0;
}

/* ============================================================================
 * 函数：sizuo
 * 参数：
 *   number - 初始的自然数
 *   step   - 迭代次数
 * 返回值：
 *   step 次迭代过程中出现的偶数个数
 * ============================================================================
 */
int sizuo(int number, int step) {
    int osu_cnt = 0;

    for (int i = 0; i <= step; i++) {
        if (number % 2 == 0) {
            osu_cnt++;
            number /= 2;
        } else {
            number = number * 3 + 1;
        }
    }

    return osu_cnt;
}
